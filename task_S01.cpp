#include <iostream>

using namespace std;

int main()
{
     int a = 10;
    double b = 3.5;
    char c = 'A';
    bool d = true;

    cout << "a = " << a << endl;
    cout << "b = " << b << endl;
    cout << "c = " << c << endl;
    cout << "d = " << d << endl;

    cout << a + b << endl;
    cout << a - b << endl;
    cout << a * b << endl;
    cout << a / b << endl;

    return 0;
}
